// Offline native masks; exact dependencies live in port/tools/package-lock.json.
import {createRequire} from 'node:module';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
import fs from 'node:fs';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const require=createRequire(path.join(root,'port/tools/package.json'));
const sharp=require('sharp'), icons=require('@fortawesome/free-solid-svg-icons');
const folder=path.join(root,'assets/k718-battery');fs.mkdirSync(folder,{recursive:true});
const nativeWidth=20, nativeHeight=15, unitsPerPixel=640/18;
const capExtension=1.5*unitsPerPixel;
let output='// Generated by scripts/generate_knob_battery.mjs; Font Awesome Free, CC BY4.0.\n#ifdef GAGGIMATE_KNOB\n#include "KnobBatteryImages.h"\n';
let header='#pragma once\n#include <lvgl.h>\n#ifdef __cplusplus\nextern "C" {\n#endif\n';
for(const name of ['Empty','Quarter','Half','ThreeQuarters','Full','Charging']){
 const icon=icons['faBattery'+(name==='Charging'?'Empty':name)].icon;
 // Lengthen only the positive terminal by1.5 native pixels, preserving its
 // corner radius, the battery body size and its original pixel scale.
 let shape=icon[4];
 const forward='c17.7 0 32 14.3 32 32l0 64c0 17.7-14.3 32-32 32';
 const reverse='c17.7 0 32-14.3 32-32l0-64c0-17.7-14.3-32-32-32';
 if(shape.includes(forward))shape=shape.replace(forward,`h${capExtension}${forward}h${-capExtension}`);
 else if(shape.includes(reverse))shape=shape.replace(reverse,`h${capExtension}${reverse}h${-capExtension}`);
 else throw Error('Unrecognized Font Awesome battery terminal');
 // The filled FA glyphs have a different baseline from battery-empty.
 const offset=name==='Empty'||name==='Charging'?0:32;
 let paths=`<path fill="white" transform="translate(0 ${offset})" d="${shape}"/>`;
 if(name==='Charging'){
  const bolt=icons.faBolt.icon, scaleY=256/bolt[1], scaleX=scaleY*0.8;
  paths+=`<path fill="white" transform="translate(${320-bolt[0]*scaleX/2} 160) scale(${scaleX} ${scaleY})" d="${bolt[4]}"/>`;
 }
 const viewHeight=nativeHeight*unitsPerPixel;
 const svg=`<svg xmlns="http://www.w3.org/2000/svg" width="${nativeWidth*8}" height="${nativeHeight*8}" viewBox="0 ${288-viewHeight/2} ${nativeWidth*unitsPerPixel} ${viewHeight}">${paths}</svg>`;
 const slug=name.replace(/[A-Z]/g,c=>'-'+c.toLowerCase()).slice(1);
 fs.writeFileSync(path.join(folder,'battery-'+slug+'.svg'),svg+'\n');
 const original=await sharp(Buffer.from(svg)).resize(27,20,{fit:'fill',kernel:'lanczos3'}).png().toBuffer();
 const native=await sharp(original).resize(nativeWidth,nativeHeight,{fit:'fill',kernel:'lanczos3'}).ensureAlpha().png().toBuffer();
 fs.writeFileSync(path.join(folder,'battery-'+slug+'-20x15.png'),native);
 const {data,info}=await sharp(native).ensureAlpha().raw().toBuffer({resolveWithObject:true});
 const count=nativeWidth*nativeHeight;
 const alpha=Array.from({length:count},(_,i)=>data[i*info.channels+3]), symbol='knob_battery_'+name.toLowerCase();
 output+=`static const uint8_t ${symbol}_data[] = {\n`;
 for(let i=0;i<count;i+=nativeWidth)output+='    '+alpha.slice(i,i+nativeWidth).join(', ')+',\n';
 output+=`};\nconst lv_img_dsc_t ${symbol}={.header.cf=LV_IMG_CF_ALPHA_8BIT,.header.always_zero=0,.header.reserved=0,.header.w=${nativeWidth},.header.h=${nativeHeight},.data_size=${count},.data=${symbol}_data};\n`;
 header+=`extern const lv_img_dsc_t ${symbol};\n`;
}
fs.writeFileSync(path.join(root,'src/display/ui/default/KnobBatteryImages.c'),output+'#endif\n');
fs.writeFileSync(path.join(root,'src/display/ui/default/KnobBatteryImages.h'),header+'#ifdef __cplusplus\n}\n#endif\n');
fs.copyFileSync(path.join(root,'port/tools/node_modules/@fortawesome/free-solid-svg-icons/LICENSE.txt'),path.join(folder,'LICENSE-FontAwesome.txt'));
fs.writeFileSync(path.join(folder,'README.txt'),'Font Awesome Free battery/bolt glyphs, CC BY4.0.\nSource: locally installed @fortawesome/free-solid-svg-icons. Charging combines battery-empty and bolt.\nTerminal extended1.5 native pixels; bolt width reduced20%; fill glyph baselines aligned.\nBody pixel scale preserved; native20x15 canvas includes the longer terminal. Offline Lanczos filtering.\nChecked-in ALPHA8 masks; no runtime SVG rendering or UI scaling.\n');
console.log('Generated6 native20x15 battery masks: longer terminal, slimmer bolt.');
